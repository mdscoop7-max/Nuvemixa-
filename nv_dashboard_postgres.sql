BEGIN;

CREATE SCHEMA IF NOT EXISTS nuvemixa_dashboard;

CREATE TABLE IF NOT EXISTS nuvemixa_dashboard.storefront_visits (
    traffic text NOT NULL,
    day text NOT NULL,
    marker text NOT NULL,
    measured_at text NOT NULL,
    PRIMARY KEY (traffic, day, marker)
);

CREATE TABLE IF NOT EXISTS nuvemixa_dashboard.webshop_daily_visitors (
    day text NOT NULL,
    visitor text NOT NULL,
    first_seen text NOT NULL,
    pageviews integer NOT NULL DEFAULT 0,
    last_path text NOT NULL DEFAULT '',
    last_at text NOT NULL DEFAULT '',
    PRIMARY KEY (day, visitor)
);

CREATE TABLE IF NOT EXISTS nuvemixa_dashboard.product_dossier_offers (
    candidate_id bigint NOT NULL, market text NOT NULL, payload text NOT NULL,
    PRIMARY KEY (candidate_id, market)
);

SET LOCAL search_path TO nuvemixa_dashboard, pg_catalog;

CREATE TABLE IF NOT EXISTS staff (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email text NOT NULL UNIQUE, name text NOT NULL, password_hash text NOT NULL,
    role text NOT NULL DEFAULT 'viewer', active integer NOT NULL DEFAULT 1,
    username text, session_version text NOT NULL DEFAULT '', permissions text
);
CREATE UNIQUE INDEX IF NOT EXISTS dashboard_staff_email ON staff (lower(email));
CREATE UNIQUE INDEX IF NOT EXISTS dashboard_staff_username ON staff (lower(username));

CREATE TABLE IF NOT EXISTS coupons (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code text NOT NULL UNIQUE, kind text NOT NULL, amount numeric NOT NULL,
    starts text, ends text, usage_limit bigint, used bigint NOT NULL DEFAULT 0, active integer NOT NULL DEFAULT 1
);
CREATE TABLE IF NOT EXISTS visits (
    day text NOT NULL, visitor text NOT NULL, views bigint NOT NULL DEFAULT 1,
    PRIMARY KEY(day, visitor)
);
CREATE TABLE IF NOT EXISTS seo_scans (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at text NOT NULL DEFAULT CURRENT_TIMESTAMP::text, payload text NOT NULL
);
CREATE TABLE IF NOT EXISTS catalog_edits (
    kind text NOT NULL, category text NOT NULL, slug text NOT NULL, payload text NOT NULL,
    position bigint GENERATED BY DEFAULT AS IDENTITY,
    PRIMARY KEY(kind, category, slug)
);
ALTER TABLE catalog_edits ADD COLUMN IF NOT EXISTS position bigint GENERATED BY DEFAULT AS IDENTITY;
CREATE TABLE IF NOT EXISTS customers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL, email text NOT NULL UNIQUE, password_hash text NOT NULL, created_at text NOT NULL DEFAULT CURRENT_TIMESTAMP::text
);
CREATE TABLE IF NOT EXISTS nv_customer_activity (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id bigint NOT NULL, event_type text NOT NULL, occurred_at text NOT NULL
);
CREATE TABLE IF NOT EXISTS suppliers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL UNIQUE, contact_email text NOT NULL DEFAULT '', website text NOT NULL DEFAULT '', notes text NOT NULL DEFAULT '',
    status text NOT NULL DEFAULT 'onderzoek', updated_at text NOT NULL DEFAULT CURRENT_TIMESTAMP::text
);
CREATE TABLE IF NOT EXISTS research_notes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category text NOT NULL, product_name text NOT NULL, supplier_id bigint REFERENCES suppliers(id),
    purchase_cost_cents bigint, shipping_cost_cents bigint, selling_price_cents bigint,
    source text NOT NULL DEFAULT '', notes text NOT NULL DEFAULT '', updated_at text NOT NULL DEFAULT CURRENT_TIMESTAMP::text
);
CREATE TABLE IF NOT EXISTS market_research (
    market text NOT NULL, product text NOT NULL, data text NOT NULL, updated_at text NOT NULL DEFAULT CURRENT_TIMESTAMP::text,
    PRIMARY KEY(market, product)
);
CREATE TABLE IF NOT EXISTS viral_candidates (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title text NOT NULL, country text NOT NULL, niche text NOT NULL, notes text NOT NULL, assessment text NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS dashboard_viral_candidate ON viral_candidates (lower(title), country);
CREATE TABLE IF NOT EXISTS viral_observations (
    candidate bigint NOT NULL REFERENCES viral_candidates(id), platform text NOT NULL,
    source text NOT NULL, observed text NOT NULL, "window" integer NOT NULL,
    metric text NOT NULL, value bigint NOT NULL, estimate integer NOT NULL,
    PRIMARY KEY(candidate, platform, source, observed, "window", metric)
);

-- Maintain defaults on schemas created from the earlier dashboard review.
ALTER TABLE seo_scans ALTER COLUMN created_at SET DEFAULT CURRENT_TIMESTAMP::text;
ALTER TABLE customers ALTER COLUMN created_at SET DEFAULT CURRENT_TIMESTAMP::text;
ALTER TABLE suppliers ALTER COLUMN contact_email SET DEFAULT '',
    ALTER COLUMN website SET DEFAULT '', ALTER COLUMN notes SET DEFAULT '',
    ALTER COLUMN status SET DEFAULT 'onderzoek',
    ALTER COLUMN updated_at SET DEFAULT CURRENT_TIMESTAMP::text;
ALTER TABLE research_notes ALTER COLUMN source SET DEFAULT '',
    ALTER COLUMN notes SET DEFAULT '', ALTER COLUMN updated_at SET DEFAULT CURRENT_TIMESTAMP::text;
ALTER TABLE market_research ALTER COLUMN updated_at SET DEFAULT CURRENT_TIMESTAMP::text;

CREATE TABLE IF NOT EXISTS supplier_comparisons (
    candidate_id bigint NOT NULL, market text NOT NULL, supplier_key text NOT NULL,
    payload text NOT NULL, PRIMARY KEY (candidate_id, market, supplier_key)
);

COMMIT;
